-- CloudCost Insight MVP: 연결 · EC2 인스턴스 · 시간별 사용량 · 수집 기록 · 단가 캐시
-- PostgreSQL과 H2(테스트) 양쪽에서 동작하는 표준 SQL만 쓴다.
-- 저장 금지: access key, secret key, session token 등 자격증명 컬럼은 어떤 이름으로도 만들지 않는다 (docs/SECURITY.md).

CREATE TABLE users
(
    id         VARCHAR(64) PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE aws_accounts
(
    id                     UUID PRIMARY KEY,
    owner_id               VARCHAR(64)              NOT NULL REFERENCES users (id),
    region                 VARCHAR(32)              NOT NULL,
    external_id            VARCHAR(64)              NOT NULL,
    role_arn               VARCHAR(2048),
    aws_account_id         VARCHAR(12),
    status                 VARCHAR(16)              NOT NULL,
    last_error_code        VARCHAR(64),
    last_error_message     VARCHAR(1000),
    verified_at            TIMESTAMP WITH TIME ZONE,
    instances_refreshed_at TIMESTAMP WITH TIME ZONE,
    usage_refreshed_at     TIMESTAMP WITH TIME ZONE,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_aws_accounts_external_id UNIQUE (external_id),
    CONSTRAINT ck_aws_accounts_status CHECK (status IN ('PENDING', 'ACTIVE', 'ERROR'))
);
CREATE INDEX idx_aws_accounts_owner ON aws_accounts (owner_id);

CREATE TABLE ec2_instances
(
    id                      UUID PRIMARY KEY,
    owner_id                VARCHAR(64)              NOT NULL,
    account_id              UUID                     NOT NULL REFERENCES aws_accounts (id),
    instance_id             VARCHAR(32)              NOT NULL,
    name                    VARCHAR(256),
    instance_type           VARCHAR(64)              NOT NULL,
    region                  VARCHAR(32)              NOT NULL,
    availability_zone       VARCHAR(32),
    state                   VARCHAR(32)              NOT NULL,
    launch_time             TIMESTAMP WITH TIME ZONE,
    platform_details        VARCHAR(128),
    tenancy                 VARCHAR(16),
    spot                    BOOLEAN                  NOT NULL,
    detailed_monitoring     BOOLEAN                  NOT NULL,
    present                 BOOLEAN                  NOT NULL,
    active_since_usage_sync BOOLEAN                  NOT NULL,
    usage_collected_until   TIMESTAMP WITH TIME ZONE,
    first_seen_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_ec2_instances_account_instance UNIQUE (account_id, instance_id)
);
CREATE INDEX idx_ec2_instances_owner_account ON ec2_instances (owner_id, account_id);

CREATE TABLE ec2_usage_hourly
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     VARCHAR(64)              NOT NULL,
    account_id   UUID                     NOT NULL REFERENCES aws_accounts (id),
    instance_id  VARCHAR(32)              NOT NULL,
    hour_start   TIMESTAMP WITH TIME ZONE NOT NULL,
    sample_count NUMERIC(10, 2)           NOT NULL,
    collected_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_ec2_usage_hourly UNIQUE (account_id, instance_id, hour_start)
);
CREATE INDEX idx_ec2_usage_hourly_owner_account_hour ON ec2_usage_hourly (owner_id, account_id, hour_start);

CREATE TABLE sync_jobs
(
    id                  UUID PRIMARY KEY,
    owner_id            VARCHAR(64)              NOT NULL,
    account_id          UUID                     NOT NULL REFERENCES aws_accounts (id),
    trigger_type        VARCHAR(16)              NOT NULL,
    status              VARCHAR(16)              NOT NULL,
    instances_refreshed BOOLEAN                  NOT NULL,
    usage_refreshed     BOOLEAN                  NOT NULL,
    ec2_request_count   INTEGER                  NOT NULL,
    cw_request_count    INTEGER                  NOT NULL,
    instance_count      INTEGER                  NOT NULL,
    usage_rows          INTEGER                  NOT NULL,
    error_code          VARCHAR(64),
    error_message       VARCHAR(1000),
    warning             VARCHAR(2000),
    started_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at         TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_sync_jobs_status CHECK (status IN ('RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED')),
    CONSTRAINT ck_sync_jobs_trigger CHECK (trigger_type IN ('QUERY', 'MANUAL'))
);
CREATE INDEX idx_sync_jobs_owner_account_started ON sync_jobs (owner_id, account_id, started_at);

-- 공개 단가 캐시 (사용자 데이터가 아니므로 owner_id가 없다)
CREATE TABLE ec2_price_cache
(
    id               UUID PRIMARY KEY,
    region           VARCHAR(32)              NOT NULL,
    instance_type    VARCHAR(64)              NOT NULL,
    operating_system VARCHAR(64)              NOT NULL,
    tenancy          VARCHAR(16)              NOT NULL,
    license_model    VARCHAR(64)              NOT NULL,
    pre_installed_sw VARCHAR(32)              NOT NULL,
    usd_per_hour     NUMERIC(14, 8),
    fetched_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_ec2_price_cache UNIQUE (region, instance_type, operating_system, tenancy, license_model,
                                          pre_installed_sw)
);
